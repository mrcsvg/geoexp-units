"""Brazil: the IBGE territorial division.

Data: a snapshot of the IBGE API de Localidades shipped with the package,
regenerated by ``scripts/fetch_ibge.py``. IBGE data is public; cite
"Fonte: IBGE". Units are keyed by the 7-digit IBGE municipality code.
"""

from __future__ import annotations

import warnings
from importlib import resources

import polars as pl
from geoexp import Hierarchy

_CSV = "ibge_municipios.csv"
_SOURCE = "ibge_municipios.source.txt"

_CURRENT = ("municipio", "regiao_imediata", "regiao_intermediaria", "uf", "regiao")
_LEGACY = ("municipio", "microrregiao", "mesorregiao", "uf", "regiao")
_LABELS = {
    "municipio": "municipio_nome",
    "regiao_imediata": "regiao_imediata_nome",
    "regiao_intermediaria": "regiao_intermediaria_nome",
    "microrregiao": "microrregiao_nome",
    "mesorregiao": "mesorregiao_nome",
    "uf": "uf_sigla",
    "regiao": "regiao_nome",
}
_CODES = (
    "municipio",
    "regiao_imediata",
    "regiao_intermediaria",
    "microrregiao",
    "mesorregiao",
    "uf",
    "regiao",
)


def _data() -> tuple[pl.DataFrame, str]:
    folder = resources.files("geoexp_units") / "data" / "br"
    frame = pl.read_csv(
        folder.joinpath(_CSV).read_bytes(),
        schema_overrides={c: pl.Int64 for c in _CODES},
    )
    source = folder.joinpath(_SOURCE).read_text(encoding="utf-8").strip()
    return frame, source


def ibge(*, legacy: bool = False) -> Hierarchy:
    """IBGE hierarchy of Brazilian municipalities.

    Parameters
    ----------
    legacy : bool, default False
        ``False``: the current division (2017 onwards) ---
        ``municipio -> regiao_imediata -> regiao_intermediaria -> uf -> regiao``,
        which covers every municipality. ``True``: the older
        ``municipio -> microrregiao -> mesorregiao -> uf -> regiao``, still
        common in published statistics. IBGE froze it in 2017, so
        municipalities created since have no micro- or mesorregiao; they are
        left out, with a warning naming them, rather than given one.

    Returns
    -------
    geoexp.Hierarchy
        Named ``"br.ibge"``; codes are ``Int64``; every level carries a label
        (names, and the two-letter abbreviation for ``uf``).

    Warns
    -----
    UserWarning
        With ``legacy=True``, for the municipalities left out.
    """
    frame, source = _data()
    levels = _LEGACY if legacy else _CURRENT
    if legacy:
        uncovered = frame.filter(pl.col("microrregiao").is_null())
        if uncovered.height:
            names = [
                f"{row['municipio_nome']} ({row['uf_sigla']}, {row['municipio']})"
                for row in uncovered.iter_rows(named=True)
            ]
            warnings.warn(
                f"{uncovered.height} municipality(ies) have no legacy micro/mesorregiao "
                f"and are left out: {names}",
                UserWarning,
                stacklevel=2,
            )
            frame = frame.filter(pl.col("microrregiao").is_not_null())
    return Hierarchy.from_frame(
        frame,
        levels=levels,
        labels={level: _LABELS[level] for level in levels},
        name="br.ibge",
        source=source,
    )
